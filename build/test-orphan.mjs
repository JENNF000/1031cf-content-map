import { chromium } from 'playwright';
import http from 'node:http'; import fs from 'node:fs'; import path from 'node:path';
const DIST=path.resolve('..');
const MIME={'.html':'text/html','.js':'text/javascript','.json':'application/json','.webmanifest':'application/manifest+json','.png':'image/png','.svg':'image/svg+xml','.txt':'text/plain'};
const s=http.createServer((q,r)=>{let p=decodeURIComponent(q.url.split('?')[0]);if(p==='/')p='/index.html';const f=path.join(DIST,p);if(!fs.existsSync(f)||fs.statSync(f).isDirectory()){r.writeHead(404);return r.end();}r.writeHead(200,{'content-type':MIME[path.extname(f)]||'application/octet-stream','cache-control':'no-cache'});fs.createReadStream(f).pipe(r);});
await new Promise(r=>s.listen(8096,r));
const b=await chromium.launch({executablePath:'/opt/pw-browsers/chromium'});
const c=await b.newContext({viewport:{width:1400,height:950}});
const p=await c.newPage();
const errs=[]; p.on('pageerror',e=>errs.push(e.message));
await p.goto('http://localhost:8096/',{waitUntil:'networkidle'});
await p.waitForSelector('#boot.off',{state:'attached'});
// annotate a page, then remove it from data.json and refresh
await p.locator('.matrix .cell .notebtn').first().click();
await p.waitForSelector('#drawer.on');
const target=await p.locator('#dpath').textContent();
await p.locator('#dstatus button',{hasText:'To do'}).click();
await p.fill('#dcomment','Notes that must outlive the page.');
await p.click('#dpost'); await p.waitForTimeout(400); await p.click('#dclose');

const orig=fs.readFileSync(path.join(DIST,'data.json'),'utf8');
const d=JSON.parse(orig); d.pages=d.pages.filter(x=>x.path!==target); d.stats.generated='2026-08-17 15:00 UTC';
fs.writeFileSync(path.join(DIST,'data.json'),JSON.stringify(d));
await p.click('#refresh'); await p.waitForTimeout(1500);
await p.locator('nav.tabs button[data-tab="notes"]').click(); await p.waitForTimeout(300);
const cards=await p.locator('#notelist .notecard').count();
const gone=await p.locator('#notelist .notecard.gonecard').count();
console.log(`cards=${cards} gonecards=${gone}`);
await p.locator('.notecard.gonecard').click(); await p.waitForTimeout(400);
const opened=await p.locator('#drawer').evaluate(n=>n.classList.contains('on'));
const comments=await p.locator('#dthread li').count();
const banner=await p.locator('#dmeta').textContent();
console.log(`drawer opens on orphan: ${opened}; comments preserved: ${comments}; banner: ${banner.trim().slice(0,40)}`);
await p.screenshot({path:'shots/orphan.png'});
fs.writeFileSync(path.join(DIST,'data.json'),orig);
console.log('pageerrors:', errs.length ? errs : 'none');
const pass = cards===1 && gone===1 && opened && comments===1 && banner.includes('No longer');
console.log(pass?'✅ orphan handling OK':'❌ orphan handling FAILED');
await b.close(); s.close(); process.exit(pass?0:1);
